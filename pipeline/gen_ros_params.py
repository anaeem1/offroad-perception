"""Generate the ROS 2 parameter file for a RELLIS-3D sequence from the repo's single sources of truth:
config/class_costs.yaml (cost table), config/sensors.yaml (ego box), the sequence's calibration file
(extrinsics differ per sequence), and the fusion settings selected on 00001 val.

  python -m pipeline.gen_ros_params --seq 00001   -> src/offroad_perception/config/perception_00001.yaml
"""
import argparse
from pathlib import Path

import yaml

from pipeline.bev import load_costs
from pipeline.fusion import ONTOLOGY_IDS
from pipeline.rellis import DATA_ROOT

REPO = Path(__file__).resolve().parents[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seq", required=True)
    ap.add_argument("--memory-s", type=float, default=5.0)
    args = ap.parse_args()
    cost, obstacle = load_costs()
    tf = yaml.safe_load(open(DATA_ROOT / f"rellis3d/calib/Rellis_3D/{args.seq}/transforms.yaml"))["os1_cloud_node-pylon_camera_node"]
    ego = yaml.safe_load(open(REPO / "config/sensors.yaml"))["ego_box_base_link"]
    ego_box = [float(v) for axis in "xyz" for v in ego[axis]]
    params = {
        "segmentation_fusion": {"ros__parameters": {
            "fusion_alpha": 0.5, "fusion_loglinear": True, "pitch_correction_deg": -0.5,
            "camera_match_window_s": 0.05, "base_frame": "base_link",
            "lidar_to_camera_q_xyzw": [float(tf["q"][k]) for k in "xyzw"],
            "lidar_to_camera_t_xyz": [float(tf["t"][k]) for k in "xyz"],
            "ego_box": ego_box}},
        "bev_tracker": {"ros__parameters": {
            "grid_extent_m": 40.0, "grid_resolution_m": 0.2, "obstacle_height_m": 0.3, "memory_max_age_s": args.memory_s,
            "cost_lut": [int(c) for c in cost], "obstacle_lut": [bool(b) for b in obstacle]}},
        "health_monitor": {"ros__parameters": {"sensor_timeout_s": 0.25, "camera_degraded_age_s": 0.15,
                                               "max_output_age_s": 0.25, "lidar_min_valid_fraction": 0.2}},
        "planner_consumer": {"ros__parameters": {"v_max": 2.0, "lidar_only_speed_factor": 0.5, "corridor_half_width_m": 0.9,
                                                 "corridor_start_m": float(ego["x"][1]), "lookahead_m": 15.0,
                                                 "stop_distance_m": 2.0, "speed_gain": 0.5, "existence_gate": 0.5,
                                                 "max_output_age_s": 0.25}},
    }
    out = REPO / f"src/offroad_perception/config/perception_{args.seq}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# GENERATED by pipeline/gen_ros_params.py --seq {args.seq}; do not edit by hand.\n"
              f"# cost_lut / obstacle_lut are in ontology-id order: {ONTOLOGY_IDS.tolist()}\n")
    out.write_text(header + yaml.safe_dump(params, sort_keys=False))
    print("wrote", out)


if __name__ == "__main__":
    main()
